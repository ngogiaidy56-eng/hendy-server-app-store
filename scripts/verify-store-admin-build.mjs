import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";

const read = (path) => readFileSync(path, "utf8");
const storeHtml = read("dist/index.html");
const adminHtml = read("dist/admin.html");
const storeEntry = read("src/main.tsx");
const adminEntry = read("src/admin-main.tsx");
const publicApp = read("src/App.tsx");
const viteConfig = read("vite.config.ts");
const worker = read("src/worker.ts");
const wrangler = read("wrangler.toml");
const bootstrapWrangler = read("wrangler.bootstrap.toml");
const deployWorkflow = read(".github/workflows/deploy-cloudflare.yml");
const packageJson = JSON.parse(read("package.json"));

assert.notEqual(storeHtml, adminHtml, "Storefront and Admin must be separate HTML documents");
assert.match(storeHtml, /Hendy Tools Platform|Hendy Store/, "Storefront branding must exist");
assert.match(adminHtml, /Hendy Admin Console/, "Admin branding must exist");
assert.match(storeHtml, /\/assets\/[^" ]+\.js/, "Storefront JavaScript bundle must be emitted");
assert.match(adminHtml, /\/assets\/[^" ]+\.js/, "Admin JavaScript bundle must be emitted");
assert.match(storeEntry, /\.\/store\.css/, "Storefront entry must import its stylesheet");
assert.match(adminEntry, /StudioWorkspace/, "Admin entry must mount the Admin Console");
assert.match(adminEntry, /\.\/admin\.css/, "Admin entry must import its stylesheet");
assert.match(publicApp, /StorefrontV2/, "Public app must mount the release-driven Storefront");
assert.doesNotMatch(publicApp, /StudioWorkspace|ServerPlusConsole|SecurityGate/, "Public bundle must not mount Admin UI or client-side fake gate");
assert.match(viteConfig, /index\.html/, "Vite must include Store entry");
assert.match(viteConfig, /admin\.html/, "Vite must include Admin entry");
assert.match(worker, /adminAccessPage\(denied\.status\)/, "Worker must fail closed for unauthenticated Admin routes");
assert.match(worker, /CF_ACCESS_ADMIN_EMAILS/, "Worker must enforce the Admin email allow-list");
assert.match(worker, /function runtimeChecks\(env: Env\)/, "Worker must expose readiness checks");
assert.match(worker, /\/api\/v1\/runtime\/readiness/, "Worker must expose readiness endpoint");
assert.match(worker, /authorizeCiPublisher\(request, env\)/, "CI publish endpoint must validate a server-side token");
assert.match(wrangler, /main = "\.\/src\/worker\.ts"/, "Production config must deploy the Worker entry");
assert.match(wrangler, /directory = "\.\/\.worker-dist"/, "Production config must serve Worker Static Assets");
assert.match(wrangler, /RELEASES_BUCKET/, "Production config must bind R2");
assert.match(bootstrapWrangler, /directory = "\.\/\.worker-dist"/, "Bootstrap config must use prepared static assets");
assert.match(deployWorkflow, /wrangler\.toml/, "CI must deploy the production Worker config");
assert.match(deployWorkflow, /provision-cloudflare-access\.mjs/, "CI must provision Access before production deploy");
assert.match(deployWorkflow, /smoke-test-cloudflare\.mjs/, "CI must run live Worker smoke tests");
assert.equal("express" in packageJson.dependencies, false, "Express must not be installed as a runtime web server");
assert.equal(existsSync("server.ts"), false, "No separate Node server source should remain");
assert.equal(existsSync(".github/workflows/deploy-render.yml"), false, "No Render deployment workflow should remain");
assert.equal(existsSync("functions/api/[[path]].ts"), false, "No Pages-only API proxy should remain");
assert.equal(existsSync("wrangler.pages.toml"), false, "No separate Pages deployment config should remain");
assert.equal(existsSync("wrangler.worker.toml"), false, "Use a single canonical Worker config");

console.log("Verified: independent Store/Admin entrypoints, Worker Static Assets, R2, Access, and Cloudflare-only deployment.");
