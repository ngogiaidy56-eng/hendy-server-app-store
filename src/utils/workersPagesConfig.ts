/** Returns an illustrative Pages config. Account-specific bindings are generated by automation/provision-cloudflare-resources.mjs. */
export function generateWranglerConfig(config: CloudflareWorkersPagesConfig): string {
  return [
    "# Cloudflare Pages with Pages Functions",
    'name = "' + safe(config.projectName || "hendy-app-store") + '"',
    'pages_build_output_dir = "./dist"',
    'compatibility_date = "2026-10-26"',
    'compatibility_flags = ["nodejs_compat"]',
    "",
    "[vars]",
    'APP_NAME = "Hendy App Store"',
    'ENVIRONMENT = "production"',
    'PUBLIC_BASE_URL = "https://' + safe(config.pagesDomain || "hendy-app-store.pages.dev") + '"',
    "",
    "# D1 / R2 / KV IDs are injected by the Cloudflare provisioning script.",
    ""
  ].join("\n");
}
function safe(value: string): string {
  return String(value || "").replace(/["\r\n]/g, "").slice(0, 160);
}

